c = 0
paragraphs = list(doc.paragraphs)
for i, p in enumerate(paragraphs):
    t = p.text
    if not t or '【F' not in t:
        continue
    for fnum, cn in translations.items():
        if f'【{fnum}】' in t:
            if i + 1 < len(paragraphs):
                np = paragraphs[i + 1]
                if np.text.strip() and '【F' not in np.text:
                    np.text = cn
                    c += 1
            break

